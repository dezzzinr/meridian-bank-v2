import assert from "node:assert/strict";
import { randomBytes } from "node:crypto";
import { and, eq, inArray } from "drizzle-orm";
import { loadDatabaseEnvironment } from "../scripts/lib/environment";

async function main() {
  const target = loadDatabaseEnvironment();
  if (!["127.0.0.1", "localhost", "::1"].includes(target.host)) throw new Error("This test creates disposable fixtures only on local PostgreSQL, never a live/shared database.");
  const { db, pool } = await import("@/db");
  const schema = await import("@/db/schema");
  const { hashPassword } = await import("@/lib/password");
  const { PDFDocument } = await import("pdf-lib");
  const ids: number[] = [];
  const password = randomBytes(20).toString("hex");
  type Client = { userId: number; token: string; email: string };
  const request = async (client: Client | null, path: string, method = "GET", body?: unknown) => fetch(`http://localhost:3000${path}`, { method, headers: { "Content-Type": "application/json", ...(client ? { "x-meridian-session": client.token } : {}) }, body: body === undefined ? undefined : JSON.stringify(body) });
  const json = async (client: Client, path: string, method = "GET", body?: unknown, expected = 200) => {
    const response = await request(client, path, method, body);
    const value = await response.json();
    assert.equal(response.status, expected, `${method} ${path}: ${JSON.stringify(value)}`);
    return value;
  };
  const createUser = async (): Promise<Client> => {
    const email = `card-test-${randomBytes(5).toString("hex")}@example.test`;
    const [user] = await db.insert(schema.users).values({ name: "Card test customer", email, passwordHash: hashPassword(password) }).returning({ id: schema.users.id });
    ids.push(user.id);
    const login = await request(null, "/api/auth/login", "POST", { email, password });
    assert.equal(login.status, 200);
    return { userId: user.id, token: (await login.json()).token, email };
  };
  try {
    assert.equal((await request(null, "/api/cards")).status, 401);
    const owner = await createUser(); const other = await createUser();
    const open = (body: unknown) => json(owner, "/api/accounts", "POST", body, 201);
    const checking = await open({ name: "Test checking", type: "checking", amount: "1000" });
    const saving = await open({ name: "Test savings", type: "savings", amount: "0" });
    const fixed = await open({ name: "Locked deposit", type: "fixed_deposit", amount: "100", termMonths: 6 });
    const euro = await open({ name: "Euro wallet", type: "foreign_currency", currency: "EUR", amount: "75" });
    const joint = await open({ name: "Shared household", type: "joint", jointEmail: other.email, amount: "100" });
    assert.equal(euro.currency, "EUR");
    assert.equal((await json(owner, "/api/accounts")).accounts.length, 5);
    assert.equal((await json(other, "/api/accounts")).accounts.length, 0);
    await json(other, `/api/accounts/${joint.id}/statements`, "GET", undefined, 404);
    const invitation = (await json(other, "/api/accounts/invitations")).invitations[0];
    await json(owner, "/api/accounts/invitations", "PATCH", { id: invitation.id, status: "accepted" }, 409);
    await json(other, "/api/accounts/invitations", "PATCH", { id: invitation.id, status: "accepted" });
    assert.equal((await json(other, "/api/accounts")).accounts[0].id, joint.id);
    await json(other, `/api/accounts/${joint.id}/statements`);
    await json(other, `/api/accounts/${joint.id}`, "PATCH", { name: "Not owner" }, 404);
    await json(owner, "/api/transfers", "POST", { sourceAccountId: fixed.id, destinationType: "account", destinationId: saving.id, amount: "1" }, 409);
    await json(owner, "/api/transfers", "POST", { sourceAccountId: checking.id, destinationType: "account", destinationId: fixed.id, amount: "1" }, 409);
    await json(owner, "/api/transfers", "POST", { sourceAccountId: checking.id, destinationType: "account", destinationId: euro.id, amount: "1" }, 400);
    const otherAccount = await json(other, "/api/accounts", "POST", { name: "Own checking", amount: "0" }, 201);
    await json(other, "/api/transfers", "POST", { sourceAccountId: joint.id, destinationType: "account", destinationId: otherAccount.id, amount: "10" }, 201);
    assert.equal((await json(owner, `/api/accounts/${joint.id}/statements`)).closingCents, 9000);
    console.log("PASS: five account types, explicit joint consent, shared payments, fixed lock and FX guard");

    const card = await json(owner, "/api/cards", "POST", { kind: "virtual", name: "Test virtual", accountId: checking.id }, 201);
    await json(owner, "/api/cards", "POST", { kind: "virtual", name: "Invalid link", accountId: fixed.id }, 400);
    await json(other, "/api/cards", "POST", { kind: "virtual", name: "Invalid ownership", accountId: checking.id }, 404);
    const listing = await json(owner, "/api/cards");
    assert.doesNotMatch(JSON.stringify(listing), /demoNumber|pinHash|passwordHash/);
    await json(other, `/api/cards/${card.id}`, "PATCH", { status: "frozen" }, 404);
    await json(other, `/api/cards/${card.id}/reveal`, "POST", { password }, 404);
    await json(owner, `/api/cards/${card.id}/reveal`, "POST", { password: "wrong-password" }, 403);
    const revealResponse = await request(owner, `/api/cards/${card.id}/reveal`, "POST", { password });
    assert.match(revealResponse.headers.get("cache-control") ?? "", /no-store/);
    assert.match((await revealResponse.json()).demoNumber, /^0000\d{12}$/);
    await json(owner, `/api/cards/${card.id}`, "PATCH", { status: "frozen" });
    const simulate = (id: number, body: Record<string, unknown> = {}) => json(owner, `/api/cards/${id}/simulate`, "POST", { merchant: "Demo store", amount: "10", channel: "online", international: false, ...body });
    assert.equal((await simulate(card.id)).status, "declined");
    await json(owner, `/api/cards/${card.id}`, "PATCH", { status: "active", onlineEnabled: false });
    assert.match((await simulate(card.id)).declineReason, /Online payments/);
    await json(owner, `/api/cards/${card.id}`, "PATCH", { onlineEnabled: true });
    assert.match((await simulate(card.id, { international: true })).declineReason, /International/);
    await json(owner, `/api/cards/${card.id}`, "PATCH", { internationalEnabled: true, dailyLimit: "100", monthlyLimit: "200" });
    assert.equal((await simulate(card.id, { merchant: "=SUM(1+1)", amount: "25", international: true })).status, "completed");
    assert.match((await simulate(card.id, { amount: "80" })).declineReason, /Daily spending/);
    await json(owner, `/api/cards/${card.id}`, "PATCH", { dailyLimit: "500", monthlyLimit: "100" }, 400);
    const mainAccount = (await json(owner, "/api/accounts")).accounts.find((a: { id: number }) => a.id === checking.id);
    assert.equal(mainAccount.balanceCents, 97500);
    const history = (await json(owner, `/api/cards/${card.id}/activity`)).activity;
    assert.equal(history.filter((a: { status: string }) => a.status === "completed").length, 1);
    assert.ok(history.some((a: { status: string }) => a.status === "declined"));
    const parallel = await Promise.all([simulate(card.id, { amount: "50" }), simulate(card.id, { amount: "50" })]);
    assert.equal(parallel.filter((a) => a.status === "completed").length, 1);
    console.log("PASS: masked card details, ownership, reveal reauthentication, freeze, channel controls, limits and concurrent authorizations");

    const physical = await json(owner, "/api/cards", "POST", { kind: "physical", name: "Test physical", accountId: checking.id, deliveryAddress: "Demo only, 123 Test Street, London, United Kingdom" }, 201);
    let physicalCard = (await json(owner, "/api/cards")).cards.find((c: { id: number }) => c.id === physical.id);
    assert.equal(physicalCard.status, "awaiting_activation");
    assert.equal((await simulate(physical.id)).status, "declined");
    await json(owner, `/api/cards/${physical.id}/activate`, "POST", { last4: physicalCard.last4 === "0000" ? "1111" : "0000" }, 400);
    await json(owner, `/api/cards/${physical.id}/activate`, "POST", { last4: physicalCard.last4 });
    await json(owner, `/api/cards/${physical.id}/pin`, "POST", { password, pin: "7891" });
    await json(owner, `/api/cards/${physical.id}`, "PATCH", { atmEnabled: true });
    assert.match((await simulate(physical.id, { channel: "atm", pin: "0000" })).declineReason, /Incorrect PIN/);
    assert.equal((await simulate(physical.id, { channel: "atm", pin: "7891" })).status, "completed");
    await json(owner, `/api/cards/${physical.id}/wallet`, "POST", { provider: "google", enabled: true });
    physicalCard = (await json(owner, "/api/cards")).cards.find((c: { id: number }) => c.id === physical.id);
    assert.equal(physicalCard.pinSet, true); assert.equal(physicalCard.googleWalletDemo, true);
    const [stored] = await db.select({ pinHash: schema.cards.pinHash }).from(schema.cards).where(eq(schema.cards.id, physical.id));
    assert.notEqual(stored.pinHash, "7891"); assert.match(stored.pinHash ?? "", /:/);
    const replacement = await json(owner, `/api/cards/${physical.id}/replace`, "POST", { password, reason: "lost" });
    assert.ok(replacement.replacementId);
    assert.equal((await json(owner, "/api/cards")).cards.find((c: { id: number }) => c.id === physical.id).status, "replaced");
    assert.equal((await simulate(physical.id)).status, "declined");
    assert.equal((await json(owner, `/api/cards/${physical.id}/activity`)).activity.filter((a: { status: string }) => a.status === "completed").length, 1);
    console.log("PASS: physical activation, hashed PIN, ATM checks, demo wallet and replacement history");

    const statement = await json(owner, `/api/accounts/${checking.id}/statements`);
    assert.equal(statement.openingCents + statement.incomingCents - statement.outgoingCents, statement.closingCents);
    assert.equal(statement.closingCents, 91500);
    assert.ok(statement.rows.some((r: { description: string }) => r.description === "=SUM(1+1)"));
    await json(other, `/api/accounts/${checking.id}/statements`, "GET", undefined, 404);
    const csv = await request(owner, `/api/accounts/${checking.id}/statements?format=csv`);
    assert.match(csv.headers.get("content-disposition") ?? "", /attachment/);
    const csvText = await csv.text();
    assert.match(csvText, /'=SUM\(1\+1\)/);
    assert.match(csvText, /,-25\.00,/, "CSV amounts remain usable numeric columns");
    const pdf = await request(owner, `/api/accounts/${checking.id}/statements?format=pdf`);
    assert.equal(pdf.status, 200); assert.match(pdf.headers.get("content-type") ?? "", /application\/pdf/);
    assert.ok((await PDFDocument.load(await pdf.arrayBuffer())).getPageCount() >= 1);
    await json(owner, `/api/accounts/${checking.id}/statements?from=2026-02-30&to=2026-03-01`, "GET", undefined, 400);
    await json(owner, `/api/accounts/${checking.id}`, "DELETE", undefined, 409);
    const zeroCard = await json(owner, "/api/cards", "POST", { name: "Close with account", kind: "virtual", accountId: saving.id }, 201);
    await json(owner, `/api/accounts/${saving.id}`, "DELETE");
    assert.ok((await json(owner, `/api/accounts/${saving.id}`)).account.closedAt);
    await json(owner, `/api/accounts/${saving.id}/statements`);
    assert.equal((await json(owner, "/api/cards")).cards.find((c: { id: number }) => c.id === zeroCard.id).status, "closed");
    console.log("PASS: reconciled statements, CSV formula safety, PDF output, authorization and history-preserving closure");

    await db.update(schema.users).set({ status: "suspended" }).where(eq(schema.users.id, owner.userId));
    await json(owner, "/api/cards");
    await json(owner, `/api/accounts/${checking.id}/statements`);
    await json(owner, `/api/cards/${card.id}`, "PATCH", { status: "frozen" }, 403);
    await json(owner, `/api/cards/${card.id}/reveal`, "POST", { password }, 403);
    await json(owner, `/api/cards/${card.id}/simulate`, "POST", { merchant: "Not allowed", amount: "1", channel: "online", international: false }, 403);
    console.log("PASS: suspension blocks mutations but preserves cards, accounts and statements read access");
  } finally {
    if (ids.length) await db.delete(schema.users).where(inArray(schema.users.id, ids));
    await pool.end();
  }
}
main().catch((e) => { console.error(e instanceof Error ? e.message : "Cards/accounts integration test failed"); process.exitCode = 1; });
