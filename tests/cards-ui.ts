import assert from "node:assert/strict";
import { randomBytes } from "node:crypto";
import { eq } from "drizzle-orm";
import { chromium, expect } from "@playwright/test";
import { loadDatabaseEnvironment } from "../scripts/lib/environment";

async function main() {
  const target = loadDatabaseEnvironment();
  if (!["localhost", "127.0.0.1", "::1"].includes(target.host)) throw new Error("Browser fixture test only runs against a local test database.");
  const { db, pool } = await import("@/db");
  const { users } = await import("@/db/schema");
  const { hashPassword } = await import("@/lib/password");
  const password = randomBytes(20).toString("hex");
  const email = `cards-ui-${randomBytes(5).toString("hex")}@example.test`;
  const [user] = await db.insert(users).values({ name: "Alex Rivera", email, passwordHash: hashPassword(password) }).returning({ id: users.id });
  let browser: Awaited<ReturnType<typeof chromium.launch>> | null = null;
  try {
    browser = await chromium.launch({ headless: true });
    const login = await fetch("http://localhost:3000/api/auth/login", { method: "POST", headers: { "Content-Type": "application/json" }, body: JSON.stringify({ email, password }) });
    const { token } = await login.json();
    assert.ok(token);
    const created = await fetch("http://localhost:3000/api/accounts", { method: "POST", headers: { "Content-Type": "application/json", "x-meridian-session": token }, body: JSON.stringify({ name: "Everyday checking", amount: "1000" }) });
    assert.equal(created.status, 201);
    const context = await browser.newContext({ viewport: { width: 1440, height: 1000 } });
    await context.addInitScript((value) => localStorage.setItem("meridian_token", value), token);
    const page = await context.newPage();
    const errors: string[] = [];
    page.on("pageerror", (error) => errors.push(error.message));
    await page.goto("http://localhost:3000/app/accounts");
    await expect(page.getByRole("heading", { name: "Accounts", exact: true })).toBeVisible();
    await page.getByRole("button", { name: "Open an account", exact: true }).click();
    const accountDialog = page.getByRole("dialog");
    await accountDialog.getByRole("button", { name: /Foreign currency/ }).click();
    await accountDialog.getByLabel("Account name", { exact: true }).fill("Travel wallet");
    await accountDialog.getByLabel("Opening balance", { exact: true }).fill("250");
    await accountDialog.getByRole("button", { name: "Open account", exact: true }).click();
    await expect(accountDialog).not.toBeVisible();
    await expect(page.getByRole("button", { name: "Travel wallet", exact: true })).toBeVisible();
    await page.locator("article").filter({ hasText: "Travel wallet" }).getByRole("button", { name: "Statements", exact: true }).click();
    await expect(page.getByText("Statement preview", { exact: true })).toBeVisible();
    const [download] = await Promise.all([page.waitForEvent("download"), page.getByRole("dialog").getByRole("button", { name: "PDF", exact: true }).click()]);
    assert.match(download.suggestedFilename(), /\.pdf$/);
    await page.getByRole("button", { name: "Close dialog", exact: true }).click();
    await page.getByRole("link", { name: "Cards", exact: true }).click();
    await expect(page.getByRole("heading", { name: "Cards", exact: true })).toBeVisible();
    await page.getByRole("button", { name: "Get a new card", exact: true }).click();
    await page.getByLabel("Card nickname", { exact: true }).fill("Everyday card");
    await page.getByRole("button", { name: "Create demo card", exact: true }).click();
    await expect(page.getByRole("heading", { name: "Everyday card", exact: true })).toBeVisible();
    await page.getByRole("button", { name: "Freeze card", exact: true }).click();
    await expect(page.getByRole("button", { name: "Unfreeze card", exact: true })).toBeEnabled();
    await page.reload();
    await expect(page.getByRole("button", { name: "Unfreeze card", exact: true })).toBeEnabled();
    await page.getByRole("button", { name: "Unfreeze card", exact: true }).click();
    await expect(page.getByRole("button", { name: "Freeze card", exact: true })).toBeEnabled();
    await page.getByRole("switch", { name: "Online payments", exact: true }).click();
    await expect(page.getByRole("switch", { name: "Online payments", exact: true })).toHaveAttribute("aria-checked", "false");
    await expect(page.getByRole("switch", { name: "Online payments", exact: true })).toBeEnabled();
    await page.getByRole("button", { name: "Test payment", exact: true }).click();
    await page.getByLabel("Test merchant", { exact: true }).fill("Corner coffee");
    await page.getByLabel("Test amount", { exact: true }).fill("12.50");
    await page.getByRole("button", { name: "Run test payment", exact: true }).click();
    await expect(page.getByText("Declined · no funds debited", { exact: true })).toBeVisible();
    await page.getByRole("button", { name: "Done", exact: true }).click();
    await page.getByRole("switch", { name: "Online payments", exact: true }).click();
    await expect(page.getByRole("switch", { name: "Online payments", exact: true })).toBeEnabled();
    await page.getByRole("button", { name: "Show details", exact: true }).click();
    await page.getByLabel("Confirm sign-in password", { exact: true }).fill(password);
    await page.getByRole("button", { name: "Reveal for 30 seconds", exact: true }).click();
    await expect(page.locator('[aria-label="Revealed demo card number"]')).toBeVisible();
    await page.getByRole("button", { name: "Hide details", exact: true }).click();
    await expect(page.locator('[aria-label="Revealed demo card number"]')).not.toBeVisible();
    await page.getByRole("button", { name: /Google Pay.*Set up demo/ }).click();
    await expect(page.getByRole("dialog").getByRole("button", { name: /Google Pay/ })).toHaveClass(/border-brand/);
    await page.getByRole("button", { name: "Save demo setup", exact: true }).click();
    await expect(page.getByRole("button", { name: /Google Pay.*Demo setup saved/ })).toBeVisible();
    await page.getByRole("button", { name: "Edit limits", exact: true }).click();
    await page.getByLabel("Daily spending limit", { exact: true }).fill("100");
    await page.getByLabel("Monthly spending limit", { exact: true }).fill("500");
    await page.getByRole("button", { name: "Save limits", exact: true }).click();
    await expect(page.getByRole("dialog")).not.toBeVisible();
    await page.screenshot({ path: "artifacts/cards-desktop.png", fullPage: true });
    await page.setViewportSize({ width: 390, height: 844 });
    await page.screenshot({ path: "artifacts/cards-mobile.png", fullPage: true });
    const overflow = await page.evaluate(() => document.documentElement.scrollWidth > window.innerWidth + 2);
    assert.equal(overflow, false, "Cards page overflows mobile viewport");
    await page.goto("http://localhost:3000/app/accounts");
    await expect(page.getByRole("button", { name: "Travel wallet", exact: true })).toBeVisible();
    await page.screenshot({ path: "artifacts/accounts-mobile.png", fullPage: true });
    await page.setViewportSize({ width: 1440, height: 1000 });
    await page.screenshot({ path: "artifacts/accounts-desktop.png", fullPage: true });
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > window.innerWidth + 2), false);
    assert.deepEqual(errors, []);
    console.log("PASS: browser account opening, PDF download, card issuance, persistent freeze, switches, decline history, secure reveal, wallet selection, limits and mobile layout");
    await context.close();
  } finally {
    await browser?.close();
    await db.delete(users).where(eq(users.id, user.id));
    await pool.end();
  }
}
main().catch((e) => { console.error(e instanceof Error ? e.message : "Browser test failed"); process.exitCode = 1; });
